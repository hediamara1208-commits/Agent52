"""Deterministic data-quality audit of the price dataset (no model, no network).

Checks every security in data/assets_universe.csv against data/prices_daily.csv,
data/corporate_actions.csv and data/fx_usdcad_daily.csv and writes a Markdown report.
Exit code 1 if a blocking check fails, so it can gate a data refresh.

    python scripts/data_quality_audit.py            # prints the report
    python scripts/data_quality_audit.py --out docs/data_quality_report.md
"""
from __future__ import annotations

import argparse
import csv
import sys
from collections import defaultdict
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MIN_OBS = 252 * 3          # under three years of trading days: history too short for a five-year drawdown
MAX_GAP_DAYS = 7           # calendar days between two observations (long weekends and holidays fit in 5)
JUMP = 0.25                # a one-day move of the adjusted close above 25% must be looked at
STALE_DAYS = 5             # last observation this many calendar days before the dataset's last date


def rows(name: str) -> list[dict]:
    with (ROOT / "data" / name).open(newline="") as f:
        return list(csv.DictReader(f))


def audit() -> tuple[list[dict], list[str], dict]:
    universe = rows("assets_universe.csv")
    prices = defaultdict(list)
    for r in rows("prices_daily.csv"):
        prices[r["ticker"]].append(r)
    splits = defaultdict(set)
    for r in rows("corporate_actions.csv"):
        kind = (r.get("action_type") or r.get("type") or r.get("action") or "").lower()
        if "split" in kind:
            splits[r["ticker"]].add(r.get("date") or r.get("ex_date"))
    fx_dates = {r["date"] for r in rows("fx_usdcad_daily.csv")}
    last_all = max(r["date"] for rs in prices.values() for r in rs)
    table, blocking = [], []
    for a in universe:
        t, rs = a["ticker"], sorted(prices.get(a["ticker"], []), key=lambda r: r["date"])
        row = {"ticker": t, "obs": len(rs), "first": "", "last": "", "dup": 0, "bad": 0, "gaps": 0, "jumps": [], "ccy": "ok", "fx_missing": 0, "status": "analysable"}
        if not rs:
            row["status"] = "no price data"; blocking.append(f"{t}: no price rows"); table.append(row); continue
        dates = [r["date"] for r in rs]
        row["first"], row["last"] = dates[0], dates[-1]
        row["dup"] = len(dates) - len(set(dates))
        closes = []
        for r in rs:
            try:
                v = float(r["adj_close"])
            except (TypeError, ValueError):
                v = float("nan")
            if not v > 0:
                row["bad"] += 1
            closes.append(v)
        if any(r["currency"] != a["currency"] for r in rs):
            row["ccy"] = "mismatch"
        for d0, d1, c0, c1 in zip(dates, dates[1:], closes, closes[1:]):
            if (date.fromisoformat(d1) - date.fromisoformat(d0)).days > MAX_GAP_DAYS:
                row["gaps"] += 1
            if c0 > 0 and c1 > 0 and abs(c1 / c0 - 1) > JUMP:
                row["jumps"].append(f"{d1} {100 * (c1 / c0 - 1):+.0f}%" + (" (split date)" if d1 in splits[t] else ""))
        if a["currency"] == "USD":
            # Days with a USD price and no Bank of Canada rate: the toolkit carries the last rate forward.
            row["fx_missing"] = sum(1 for d in dates if d not in fx_dates)
        stale = (date.fromisoformat(last_all) - date.fromisoformat(dates[-1])).days
        problems = []
        if row["dup"]: problems.append("duplicate dates")
        if row["bad"]: problems.append("missing or non-positive prices")
        if row["ccy"] != "ok": problems.append("currency differs from the asset list")
        if stale > STALE_DAYS: problems.append(f"stale by {stale} days")
        if len(rs) < MIN_OBS: problems.append("history under three years")
        if problems:
            row["status"] = "; ".join(problems)
            blocking.append(f"{t}: {row['status']}")
        table.append(row)
    return table, blocking, {"last": last_all, "n": len(universe)}


def report(table, blocking, meta) -> str:
    out = ["# Data-quality report", "",
           f"Generated by `scripts/data_quality_audit.py` from the files in `data/`. Dataset ends {meta['last']}.",
           f"Thresholds: at least {MIN_OBS} observations, no gap above {MAX_GAP_DAYS} calendar days, one-day adjusted-close moves above {int(JUMP * 100)}% listed, last observation within {STALE_DAYS} days of the dataset end.", "",
           f"**{sum(1 for r in table if r['status'] == 'analysable')} of {meta['n']} securities pass every blocking check.**", "",
           "| Ticker | Observations | First | Last | Duplicates | Bad prices | Gaps | Currency | USD days without a BoC rate | One-day moves > 25% | Result |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in table:
        out.append(f"| {r['ticker']} | {r['obs']} | {r['first']} | {r['last']} | {r['dup']} | {r['bad']} | {r['gaps']} | {r['ccy']} | {r['fx_missing']} | {'; '.join(r['jumps']) or 'none'} | {r['status']} |")
    out += ["", "Blocking findings: " + ("none." if not blocking else ""), *[f"- {b}" for b in blocking], "",
            "Large one-day moves and gaps are listed for review, not blocked: crypto assets and single stocks do move that much, and the adjusted close already accounts for splits and dividends."]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out")
    args = ap.parse_args()
    table, blocking, meta = audit()
    text = report(table, blocking, meta)
    if args.out:
        Path(args.out).write_text(text)
    else:
        print(text)
    sys.exit(1 if blocking else 0)
